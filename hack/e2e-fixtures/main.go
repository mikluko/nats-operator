// secret is what credsSecret renders.
type secret struct {
	Name, Namespace string
	Lines           []string
}

// credsSecret renders a Secret holding creds lines under user.creds.
const credsSecret = `apiVersion: v1
kind: Secret
metadata:
  name: {{.Name}}
  namespace: {{.Namespace}}
stringData:
  user.creds: |
{{range $line := .Lines}}{{if $line}}    {{$line}}{{end}}
{{end}}`
